CREATE TABLE IF NOT EXISTS member (
 member_id BIGINT AUTO_INCREMENT PRIMARY KEY, login_id VARCHAR(50) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, name VARCHAR(50) NOT NULL, email VARCHAR(100) NOT NULL UNIQUE,
 phone VARCHAR(30) NOT NULL, address VARCHAR(255) NOT NULL, session_version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS category (category_id BIGINT AUTO_INCREMENT PRIMARY KEY, category_name VARCHAR(30) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS product (
 product_id BIGINT AUTO_INCREMENT PRIMARY KEY, category_id BIGINT NOT NULL, name VARCHAR(100) NOT NULL,
 price INT NOT NULL CHECK(price>=0), description TEXT, image VARCHAR(255), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES category(category_id)
);
CREATE TABLE IF NOT EXISTS product_variant (
 variant_id BIGINT AUTO_INCREMENT PRIMARY KEY, product_id BIGINT NOT NULL, color VARCHAR(30) NOT NULL, size VARCHAR(30) NOT NULL,
 stock INT NOT NULL DEFAULT 20 CHECK(stock>=0), UNIQUE(product_id,color,size), FOREIGN KEY(product_id) REFERENCES product(product_id)
);
CREATE TABLE IF NOT EXISTS cart (
 cart_id BIGINT AUTO_INCREMENT PRIMARY KEY, member_id BIGINT NOT NULL, variant_id BIGINT NOT NULL,
 quantity INT NOT NULL CHECK(quantity>0), UNIQUE(member_id,variant_id),
 FOREIGN KEY(member_id) REFERENCES member(member_id), FOREIGN KEY(variant_id) REFERENCES product_variant(variant_id)
);
CREATE TABLE IF NOT EXISTS outfit (
 outfit_id BIGINT AUTO_INCREMENT PRIMARY KEY, member_id BIGINT NOT NULL, title VARCHAR(100) NOT NULL, content TEXT NOT NULL,
 image LONGTEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(member_id) REFERENCES member(member_id)
);
CREATE TABLE IF NOT EXISTS outfit_product (
 outfit_product_id BIGINT AUTO_INCREMENT PRIMARY KEY, outfit_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 UNIQUE(outfit_id,product_id), FOREIGN KEY(outfit_id) REFERENCES outfit(outfit_id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES product(product_id)
);
CREATE TABLE IF NOT EXISTS outfit_like (
 like_id BIGINT AUTO_INCREMENT PRIMARY KEY, outfit_id BIGINT NOT NULL, member_id BIGINT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(outfit_id,member_id),
 FOREIGN KEY(outfit_id) REFERENCES outfit(outfit_id) ON DELETE CASCADE, FOREIGN KEY(member_id) REFERENCES member(member_id)
);
CREATE TABLE IF NOT EXISTS comment (
 comment_id BIGINT AUTO_INCREMENT PRIMARY KEY, outfit_id BIGINT NOT NULL, member_id BIGINT NOT NULL, parent_id BIGINT,
 content VARCHAR(500) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(outfit_id) REFERENCES outfit(outfit_id) ON DELETE CASCADE, FOREIGN KEY(member_id) REFERENCES member(member_id),
 FOREIGN KEY(parent_id) REFERENCES comment(comment_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS notification (
 notification_id BIGINT AUTO_INCREMENT PRIMARY KEY, member_id BIGINT NOT NULL, actor_id BIGINT NOT NULL,
 outfit_id BIGINT NOT NULL, kind VARCHAR(20) NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(member_id) REFERENCES member(member_id),
 FOREIGN KEY(actor_id) REFERENCES member(member_id), FOREIGN KEY(outfit_id) REFERENCES outfit(outfit_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS shop_order (
 order_id BIGINT AUTO_INCREMENT PRIMARY KEY, member_id BIGINT NOT NULL, recipient VARCHAR(50) NOT NULL,
 address VARCHAR(255) NOT NULL, phone VARCHAR(30) NOT NULL, email VARCHAR(100) NOT NULL, payment VARCHAR(30) NOT NULL,
 subtotal INT NOT NULL, shipping INT NOT NULL, total INT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(member_id) REFERENCES member(member_id)
);
CREATE TABLE IF NOT EXISTS order_item (
 order_item_id BIGINT AUTO_INCREMENT PRIMARY KEY, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 name VARCHAR(100) NOT NULL, color VARCHAR(30) NOT NULL, size VARCHAR(30) NOT NULL,
 price INT NOT NULL, quantity INT NOT NULL, FOREIGN KEY(order_id) REFERENCES shop_order(order_id)
);
CREATE TABLE IF NOT EXISTS recovery_token (
 token_hash VARCHAR(64) PRIMARY KEY, member_id BIGINT NOT NULL, expires_at TIMESTAMP NOT NULL,
 FOREIGN KEY(member_id) REFERENCES member(member_id) ON DELETE CASCADE
);
